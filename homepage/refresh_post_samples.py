"""Regenerate public draft examples only; do not publish posts or rerender the kit."""
from pathlib import Path
import json
from launchloom.models import Brief
from launchloom.planning import make_posts

ROOT = Path(__file__).resolve().parent
CHANNELS = ['x', 'bluesky', 'threads', 'linkedin', 'youtube', 'instagram', 'tiktok']
PUBLIC_FEATURES = {
    'ja': [('画面収録から、横動画と縦動画へ。', '製品の操作映像を使い、16:9と9:16の紹介素材を書き出します。'), ('構成を確認してから書き出す。', '見出し・字幕・素材を確認し、承認した構成で制作します。'), ('紹介ページと投稿案もまとめる。', '同じ企画からHTMLと媒体別の投稿下書きを用意します。')],
    'en': [('Turn a recording into landscape and portrait films.', 'Use recorded product interactions to export 16:9 and 9:16 launch materials.'), ('Review the plan before rendering.', 'Check the headings, captions and assets before approving the production plan.'), ('Prepare a page and social drafts too.', 'Use the same brief to prepare HTML and channel-specific post drafts.')],
}

def build_samples():
    samples = {}
    for language in ['ja', 'en']:
        brief = Brief(name='Launchloom', language=language, channels=CHANNELS,
            tagline='録画を、公開に使える素材へ。' if language == 'ja' else 'Turn recordings into launch materials.',
            audience='自分のプロダクトを紹介したい開発者' if language == 'ja' else 'developers preparing a product launch',
            product_url='https://github.com/FORIFOR/Launchloom',
            features=[dict(title=title, detail=detail, approved=True, evidence='Public capability described in the repository homepage and README') for title, detail in PUBLIC_FEATURES[language]])
        samples[language] = make_posts(brief, 'homepage-drafts-20260916')
        assert len({p['content'] for p in samples[language]}) == 7
        assert all(p['state'] == 'draft' for p in samples[language])
    return samples

def main():
    samples = build_samples()
    data = json.dumps(samples, ensure_ascii=False, separators=(',', ':'))
    script = "/* Generated by refresh_post_samples.py through make_posts. Drafts only. */\n(() => {\n'use strict';\nconst samples=" + data + ";\n"
    script += """const ja=document.documentElement.lang==='ja';
const list=document.querySelector('#view-posts .drafts'); if(!list)return;
list.replaceChildren();
for(const draft of samples[ja?'ja':'en']){
 const item=document.createElement('li'),channel=document.createElement('span'),text=document.createElement('pre');
 channel.className='ch';channel.textContent=draft.channel;text.textContent=draft.content;item.append(channel,text);list.append(item);
}
const note=ja?'7媒体向けの投稿案を、現在の投稿生成処理で再生成しました。動画・紹介ページ・配布キットは既存の例で、この更新で作り直したものではありません。':'Seven channel-specific drafts regenerated with the current post generator. The videos, landing page and downloadable kit remain the existing examples and were not rerendered by this update.';
const template=document.querySelector('template[data-caption="posts"]');if(template)template.textContent=note;
if(document.getElementById('tab-posts')?.getAttribute('aria-selected')==='true')document.getElementById('showcase-caption').textContent=note;
})();
"""
    (ROOT / 'post-drafts.js').write_text(script, encoding='utf-8')
    (ROOT / 'post-drafts.json').write_text(json.dumps({'scope':'Post drafts regenerated only; no new video, site, or kit export', 'drafts':samples}, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print('Generated 14 public draft examples with the production make_posts function.')

if __name__ == '__main__': main()
